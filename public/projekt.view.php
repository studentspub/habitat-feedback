<h1>Über das Projekt</h1>
<p>Habitat Feedback ist ein privates, <strong>unkommerzielles</strong> Projekt: eine Karte, auf der Menschen ihre eigene Straße ehrlich und anonym bewerten und die dazu zeigt, was amtliche Statistik und offene Daten über die Umgebung sagen. Es gibt keine Firma dahinter, kein Geschäftsmodell und keinen Auftraggeber. Die Seite wird von einer Privatperson gebaut und betrieben, als Beitrag für alle, die eine Wohnlage besser verstehen wollen, bevor sie dort wohnen, bauen, kaufen oder bleiben.</p>

<h2>Worum es geht</h2>
<p>Wer eine Wohnung sucht, bekommt Exposés, Fotos und Preise, aber selten eine Antwort auf die Frage, wie es sich in einer Straße tatsächlich lebt. Habitat Feedback sammelt dafür zwei Dinge an einem Ort: die Einschätzung der Menschen, die dort wohnen (fünf Kriterien, keine Kommentare, nur als Durchschnitt je Straßenabschnitt sichtbar), und die Fakten zur Umgebung aus öffentlichen Quellen: Zensus, Nahversorgung, Klima, Lärm, Verkehr, Kennzahlen des Kreises. Mehr zur Funktionsweise steht unter <a href="/ueber">Über Habitat Feedback</a>.</p>

<h2>Unkommerziell</h2>
<div class="kasten">
  <ul>
    <li><strong>Keine Werbung</strong>, kein Tracking, keine Verkaufsanzeigen.</li>
    <li><strong>Kein Verkauf von Daten.</strong> Bewertungen werden ohne Konto und ohne Klarnamen gespeichert und nur als Durchschnitt je Straßenabschnitt angezeigt; Einzelbewertungen bekommt niemand zu sehen, auch nicht der Betreiber in auswertbarer Form (siehe <a href="/datenschutz">Datenschutz</a>).</li>
    <li><strong>Kostenlos</strong> für alle, ohne Premium-Stufe.</li>
    <li><strong>Privat betrieben</strong>, aus eigener Tasche, in der Freizeit. Daraus folgt auch: keine Garantie auf Verfügbarkeit, keine Rund-um-die-Uhr-Betreuung.</li>
  </ul>
</div>

