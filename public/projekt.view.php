<h2>Mitmachen</h2>
<ul>
  <li><strong>Bewerten:</strong> Die wichtigste Hilfe ist eine ehrliche Bewertung der eigenen Straße, dauert zwei Minuten: <a href="/bewerten">Bewertung abgeben</a>.</li>
  <li><strong>Fehler und Ideen:</strong> als <a href="https://github.com/studentspub/habitat-feedback/issues" target="_blank" rel="noopener">Issue auf GitHub</a> (Konto nötig) oder per E-Mail an die Adresse im <a href="/impressum">Impressum</a>.</li>
  <li><strong>Unplausible Bewertungen melden:</strong> Link „Bewertungen melden“ im Popup eines Straßenabschnitts. Jede Meldung wird gelesen.</li>
  <li><strong>Mitentwickeln:</strong> Beiträge am Code sind willkommen, Hinweise dazu stehen im Repository (README, Issue-Vorlage, Sicherheitsrichtlinie).</li>
</ul>

<h2>Grenzen</h2>
<ul>
  <li>Bewertungen sind subjektive Eindrücke von Bewohnern, keine Messung. Sie erscheinen erst, wenn ein Abschnitt mindestens sechs Adressen und drei Bewertungen hat, damit niemand ein einzelnes Haus oder eine einzelne Person bewertet.</li>
  <li>Amtliche Zahlen haben einen Stand (steht bei jeder Kennzahl unter <a href="/quellen">Quellen &amp; Lizenzen</a>) und beziehen sich auf Gemeinde, Kreis oder Rasterzelle, nicht auf ein Haus.</li>
  <li>Keine Gewähr für Vollständigkeit oder Richtigkeit, keine Rechts-, Finanz- oder Kaufberatung. Die Karte ist eine Lesehilfe, die Entscheidung bleibt deine.</li>
  <li>Für Karte und Bewertung werden Dienste des OpenStreetMap-Projekts genutzt; deren Regeln (Fair Use, Namensnennung) gelten mit.</li>
</ul>

